use gpui::{App, KeyBinding, actions};

actions!(
    motty,
    [
        Copy,
        Paste,
        SelectAll,
        Clear,
        IncreaseFontSize,
        DecreaseFontSize,
        ResetFontSize,
        Quit,
        NewTab,
        CloseTab,
        ReopenClosedTab,
        NextTab,
        PreviousTab,
        ActivateTab1,
        ActivateTab2,
        ActivateTab3,
        ActivateTab4,
        ActivateTab5,
        ActivateTab6,
        ActivateTab7,
        ActivateTab8,
        ActivateLastTab,
        ToggleTabsPanel,
        SplitRight,
        SplitLeft,
        SplitDown,
        SplitUp,
        FocusPaneLeft,
        FocusPaneRight,
        FocusPaneUp,
        FocusPaneDown,
        FocusNextPane,
        FocusPreviousPane,
        EqualizeSplits,
        ZoomSplit,
        CursorLineStart,
        CursorLineEnd,
        CursorWordLeft,
        CursorWordRight,
        DeleteToLineStart,
        DeleteToLineEnd,
        DeleteWordLeft,
        DeleteWordRight,
        Undo,
        ScrollToTop,
        ScrollToBottom,
        ScrollPageUp,
        ScrollPageDown,
        ScrollLineUp,
        ScrollLineDown,
        NewWindow,
        CloseWindow,
        Minimize,
        ToggleFullScreen,
        MoveDividerLeft,
        MoveDividerRight,
        MoveDividerUp,
        MoveDividerDown,
        Find,
        FindNext,
        FindPrevious,
        GlobalSearch,
        ToggleViMode,
        ToggleViKeyHints,
        ToggleReadOnly,
        HintOpen,
        HintCopy,
        HintPaste,
        HintReveal,
    ]
);

pub fn bind_keys(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("cmd-c", Copy, Some("Terminal")),
        KeyBinding::new("cmd-v", Paste, Some("Terminal")),
        KeyBinding::new("cmd-a", SelectAll, Some("Terminal")),
        KeyBinding::new("cmd-k", Clear, Some("Terminal")),
        KeyBinding::new("cmd-f", Find, Some("Terminal")),
        KeyBinding::new("ctrl-shift-space", ToggleViMode, Some("Terminal")),
        KeyBinding::new("cmd-/", ToggleViKeyHints, Some("Terminal")),
        KeyBinding::new("cmd-g", FindNext, Some("Terminal")),
        KeyBinding::new("cmd-shift-g", FindPrevious, Some("Terminal")),
        KeyBinding::new("cmd-=", IncreaseFontSize, Some("Terminal")),
        KeyBinding::new("cmd-+", IncreaseFontSize, Some("Terminal")),
        KeyBinding::new("cmd--", DecreaseFontSize, Some("Terminal")),
        KeyBinding::new("cmd-0", ResetFontSize, Some("Terminal")),
        KeyBinding::new("cmd-q", Quit, None),
        KeyBinding::new("cmd-t", NewTab, Some("Workspace")),
        KeyBinding::new("cmd-w", CloseTab, Some("Workspace")),
        KeyBinding::new("cmd-shift-t", ReopenClosedTab, Some("Workspace")),
        KeyBinding::new("cmd-shift-]", NextTab, Some("Workspace")),
        KeyBinding::new("ctrl-tab", NextTab, Some("Workspace")),
        KeyBinding::new("cmd-shift-[", PreviousTab, Some("Workspace")),
        KeyBinding::new("ctrl-shift-tab", PreviousTab, Some("Workspace")),
        KeyBinding::new("cmd-1", ActivateTab1, Some("Workspace")),
        KeyBinding::new("cmd-2", ActivateTab2, Some("Workspace")),
        KeyBinding::new("cmd-3", ActivateTab3, Some("Workspace")),
        KeyBinding::new("cmd-4", ActivateTab4, Some("Workspace")),
        KeyBinding::new("cmd-5", ActivateTab5, Some("Workspace")),
        KeyBinding::new("cmd-6", ActivateTab6, Some("Workspace")),
        KeyBinding::new("cmd-7", ActivateTab7, Some("Workspace")),
        KeyBinding::new("cmd-8", ActivateTab8, Some("Workspace")),
        KeyBinding::new("cmd-9", ActivateLastTab, Some("Workspace")),
        KeyBinding::new("cmd-shift-l", ToggleTabsPanel, Some("Workspace")),
        KeyBinding::new("cmd-d", SplitRight, Some("Workspace")),
        KeyBinding::new("cmd-alt-d", SplitLeft, Some("Workspace")),
        KeyBinding::new("cmd-shift-d", SplitDown, Some("Workspace")),
        KeyBinding::new("cmd-alt-shift-d", SplitUp, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-left", FocusPaneLeft, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-right", FocusPaneRight, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-up", FocusPaneUp, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-down", FocusPaneDown, Some("Workspace")),
        KeyBinding::new("cmd-]", FocusNextPane, Some("Workspace")),
        KeyBinding::new("cmd-[", FocusPreviousPane, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-=", EqualizeSplits, Some("Workspace")),
        KeyBinding::new("cmd-shift-enter", ZoomSplit, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-shift-left", MoveDividerLeft, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-shift-right", MoveDividerRight, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-shift-up", MoveDividerUp, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-shift-down", MoveDividerDown, Some("Workspace")),
        KeyBinding::new("cmd-n", NewWindow, None),
        KeyBinding::new("cmd-shift-w", CloseWindow, Some("Workspace")),
        KeyBinding::new("cmd-m", Minimize, Some("Workspace")),
        KeyBinding::new("cmd-ctrl-f", ToggleFullScreen, Some("Workspace")),
        // Natural text editing, as Otty binds it: readline/zle keys.
        KeyBinding::new("cmd-left", CursorLineStart, Some("Terminal")),
        KeyBinding::new("cmd-right", CursorLineEnd, Some("Terminal")),
        KeyBinding::new("alt-left", CursorWordLeft, Some("Terminal")),
        KeyBinding::new("alt-right", CursorWordRight, Some("Terminal")),
        KeyBinding::new("cmd-backspace", DeleteToLineStart, Some("Terminal")),
        KeyBinding::new("cmd-delete", DeleteToLineEnd, Some("Terminal")),
        KeyBinding::new("alt-backspace", DeleteWordLeft, Some("Terminal")),
        KeyBinding::new("alt-delete", DeleteWordRight, Some("Terminal")),
        KeyBinding::new("cmd-z", Undo, Some("Terminal")),
        KeyBinding::new("cmd-home", ScrollToTop, Some("Terminal")),
        KeyBinding::new("cmd-end", ScrollToBottom, Some("Terminal")),
        KeyBinding::new("cmd-pageup", ScrollPageUp, Some("Terminal")),
        KeyBinding::new("cmd-pagedown", ScrollPageDown, Some("Terminal")),
        KeyBinding::new("cmd-alt-up", ScrollLineUp, Some("Terminal")),
        KeyBinding::new("cmd-alt-down", ScrollLineDown, Some("Terminal")),
        KeyBinding::new("cmd-alt-pageup", ScrollLineUp, Some("Terminal")),
        KeyBinding::new("cmd-alt-pagedown", ScrollLineDown, Some("Terminal")),
    ]);
}
